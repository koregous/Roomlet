import { Block, ItemIndexEntry } from './types'
import { getSupabaseClient, getSupabaseServiceClient } from './supabase'

/**
 * Extract media items from section blocks for the item index
 * Returns array of items to be inserted into item_index table
 */
export function extractMediaItems(
  sectionId: string,
  blocks: Block[],
  uploadTime: Date,
  isNsfw: boolean
): ItemIndexEntry[] {
  const items: ItemIndexEntry[] = []

  for (const block of blocks) {
    if (block.type === 'image' && block.content?.image?.url) {
      items.push({
        id: '', // Will be generated by database
        section_id: sectionId,
        block_id: block.id,
        block_type: 'image',
        item_url: block.content.image.url,
        upload_time: uploadTime,
        position: 0,
        is_nsfw: isNsfw,
        caption: block.content.image.caption,
        alt_text: block.content.image.alt,
        created_at: new Date()
      })
    }
    else if (block.type === 'gallery' && Array.isArray(block.content?.images)) {
      block.content.images.forEach((img, index) => {
        if (img?.url) {
          items.push({
            id: '', // Will be generated by database
            section_id: sectionId,
            block_id: block.id,
            block_type: 'gallery',
            item_url: img.url,
            upload_time: uploadTime,
            position: index,
            is_nsfw: isNsfw,
            caption: img.caption,
            alt_text: img.altText,
            created_at: new Date()
          })
        }
      })
    }
    else if (block.type === 'carousel' && Array.isArray(block.content?.images)) {
      block.content.images.forEach((img, index) => {
        if (img?.url) {
          items.push({
            id: '', // Will be generated by database
            section_id: sectionId,
            block_id: block.id,
            block_type: 'carousel',
            item_url: img.url,
            upload_time: uploadTime,
            position: index,
            is_nsfw: isNsfw,
            caption: img.caption,
            alt_text: img.altText,
            created_at: new Date()
          })
        }
      })
    }
  }

  return items
}

/**
 * Synchronize the item index with section blocks
 *
 * Items are matched by (block_id, item_url) - NOT by position. This keeps a
 * row's id (and everything hanging off it, e.g. likes) and its original
 * upload_time stable when the owner reorders images inside a block.
 * Moves only update `position`; caption/alt edits update in place; only
 * genuinely new URLs are inserted and genuinely removed URLs are deleted.
 *
 * Uses the service-role client: item_index has SELECT-only RLS for
 * anon/authenticated, so writes through the anon client are rejected (which
 * previously made every live sync fail silently - callers treat sync errors as
 * non-blocking). CALLERS MUST VERIFY THE USER OWNS `sectionId` BEFORE CALLING.
 */
export async function syncItemIndex(
  sectionId: string,
  blocks: Block[],
  isNsfw: boolean
): Promise<void> {
  const serviceClient = getSupabaseServiceClient()
  if (!serviceClient) {
    console.warn(
      '[syncItemIndex] SUPABASE_SERVICE_ROLE_KEY is not set - falling back to the anon client, ' +
        'which cannot write to item_index. The feed will not receive new images.'
    )
  }
  const supabase = serviceClient ?? getSupabaseClient()

  // Extract current items from blocks (using current time for new items only)
  const currentItems = extractMediaItems(sectionId, blocks, new Date(), isNsfw)

  const { data: existingItems, error: fetchError } = await supabase
    .from('item_index')
    .select('id, item_url, block_id, position, is_nsfw, caption, alt_text')
    .eq('section_id', sectionId)

  if (fetchError) {
    console.error('[syncItemIndex] Failed to fetch existing items:', fetchError)
    throw fetchError
  }

  type ExistingRow = {
    id: string
    item_url: string
    block_id: string
    position: number
    is_nsfw: boolean
    caption: string | null
    alt_text: string | null
  }

  const keyOf = (blockId: string, url: string) => `${blockId}\u0000${url}`

  // Group existing rows by (block, url), ordered by position. The same URL can
  // legitimately appear more than once in a block, so each group is a list that
  // we pair up with the current occurrences in order.
  const existingByKey = new Map<string, ExistingRow[]>()
  for (const row of (existingItems || []) as ExistingRow[]) {
    const key = keyOf(row.block_id, row.item_url)
    const list = existingByKey.get(key)
    if (list) list.push(row)
    else existingByKey.set(key, [row])
  }
  existingByKey.forEach(list => list.sort((a, b) => a.position - b.position))

  const currentByKey = new Map<string, ItemIndexEntry[]>()
  for (const item of currentItems) {
    const key = keyOf(item.block_id, item.item_url)
    const list = currentByKey.get(key)
    if (list) list.push(item)
    else currentByKey.set(key, [item])
  }

  const itemsToAdd: ItemIndexEntry[] = []
  const idsToDelete: string[] = []
  const itemsToUpdate: Array<{
    id: string
    patch: { position: number; caption: string | null; alt_text: string | null }
  }> = []

  currentByKey.forEach((currentList, key) => {
    const existingList = existingByKey.get(key) || []

    currentList.forEach((cur, i) => {
      const ex = existingList[i]
      if (!ex) {
        itemsToAdd.push(cur)
        return
      }
      const nextCaption = cur.caption ?? null
      const nextAlt = cur.alt_text ?? null
      if (
        ex.position !== cur.position ||
        (ex.caption ?? null) !== nextCaption ||
        (ex.alt_text ?? null) !== nextAlt
      ) {
        itemsToUpdate.push({
          id: ex.id,
          patch: { position: cur.position, caption: nextCaption, alt_text: nextAlt },
        })
      }
    })

    // Fewer occurrences now than before: drop the extras
    existingList.slice(currentList.length).forEach(ex => idsToDelete.push(ex.id))
  })

  // URLs that no longer exist in the block at all
  existingByKey.forEach((existingList, key) => {
    if (!currentByKey.has(key)) {
      existingList.forEach(ex => idsToDelete.push(ex.id))
    }
  })

  // Check if NSFW flag changed for existing items
  const nsfwChanged = (existingItems || []).some(item => item.is_nsfw !== isNsfw)

  // 1. Delete removed items first (frees unique (section, block, url, position) slots)
  if (idsToDelete.length > 0) {
    const { error: deleteError } = await supabase
      .from('item_index')
      .delete()
      .in('id', idsToDelete)

    if (deleteError) {
      console.error('[syncItemIndex] Failed to delete items:', deleteError)
      throw deleteError
    }
  }

  // 2. Update moved / re-captioned items in place (id + upload_time untouched).
  // Non-critical, so a failure is logged rather than failing the whole save.
  if (itemsToUpdate.length > 0) {
    const results = await Promise.all(
      itemsToUpdate.map(({ id, patch }) =>
        supabase.from('item_index').update(patch).eq('id', id)
      )
    )
    results.forEach(({ error }) => {
      if (error) console.error('[syncItemIndex] Failed to update item:', error)
    })
  }

  // 3. Insert new items
  if (itemsToAdd.length > 0) {
    // Remove id and created_at fields (database will generate them)
    const itemsForInsert = itemsToAdd.map(({ id, created_at, ...item }) => item)

    const { error: insertError } = await supabase
      .from('item_index')
      .insert(itemsForInsert)

    if (insertError) {
      console.error('[syncItemIndex] Failed to insert items:', insertError)
      throw insertError
    }
  }

  if (nsfwChanged) {
    const { error: updateError } = await supabase
      .from('item_index')
      .update({ is_nsfw: isNsfw })
      .eq('section_id', sectionId)

    if (updateError) {
      console.error('[syncItemIndex] Failed to update NSFW flag:', updateError)
      throw updateError
    }
  }
}
